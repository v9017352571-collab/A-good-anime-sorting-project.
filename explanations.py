class DatabaseManager:
    """Класс для управления базой данных аниме."""

    def __init__(self, db_name="best_anime.sqlite"):
        """Получение best_anime.sqlite и активация следующей функции"""

    def init_database(self):
        """Инициализация базы данных - создает таблицы если они не существуют.

        Создает две связанные таблицы:
        1. genres - хранит уникальные жанры с автоматическим ID
        2. animes - основная таблица с информацией об аниме, включая внешний ключ на жанр
        Внешний ключ обеспечивает целостность данных - нельзя привязать аниме к несуществующему жанру.
        """

    def get_all_films(self):
        """Получение всех аниме из базы данных с JOIN к таблице жанров.

        Использует LEFT JOIN для получения названий жанров вместо их ID.
        COALESCE обеспечивает возврат '0' вместо NULL для поля просмотров.
        Данные сортируются по ID для сохранения порядка добавления.
        """

    def add_film(self, title, year, genre_id, duration):
        """Добавление нового аниме в базу данных.

        Устанавливает счетчик просмотров в '0' по умолчанию.
        Использует параметризованный запрос для защиты от SQL-инъекций.
        Возвращает True при успешном добавлении, False при ошибке.
        """

    def delete_film(self, film_id):
        """Удаление аниме по ID с проверкой существования записи.

        cursor.rowcount > 0 гарантирует, что запись существовала и была удалена.
        conn.rollback() откатывается при ошибке для сохранения целостности данных.
        """

    def get_all_genres(self):
        """Получение всех жанров из базы с сортировкой по алфавиту.

        Возвращает список кортежей (id, title) для заполнения комбо-боксов в интерфейсе.
        Сортировка ORDER BY title улучшает UX при работе с выпадающими списками.
        """

    def increment_views(self, film_id):
        """Безопасное увеличение счетчика просмотров на 1.

        Использует COALESCE для обработки возможных NULL-значений.
        Преобразует значение в число для инкремента, затем обратно в строку для хранения.
        Такой подход необходим из-за TEXT-типа поля prosmotrs в схеме БД.

        Сейчас уже не актуально видь у всех фильмов как минимум больше 100
        просмотров, но упаменуть стоит.
        """

    def update_film_poster(self, film_id, image_path):
        """Загрузка и сохранение изображения постера в формате BLOB.

        Читает файл в бинарном режиме для корректной обработки всех форматов изображений.
        Обрабатывает исключения для предотвращения повреждения БД при ошибках чтения файла.
        """

    def update_film_genre(self, film_id, genre_name):
        """Обновление жанра по названию вместо ID.

        Сначала находит ID жанра по названию, что упрощает работу с интерфейсом.
        Проверяет существование жанра перед обновлением для сохранения целостности данных.
        Возвращает False если жанр не найден, предотвращая некорректные ссылки.
        """



